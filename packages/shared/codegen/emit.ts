import ts from 'typescript';
import type { Operation } from './operations';

export const HEADER = '// This file is auto-generated by @hey-api/openapi-ts';

const CLIENT_MODULE = '@sitecore-marketplace-sdk/client';

const LINE_SEPARATOR = String.fromCharCode(0x2028);
const PARAGRAPH_SEPARATOR = String.fromCharCode(0x2029);

/**
 * Line breaks recognized by the TypeScript printer.
 */
const LINE_BREAK = new RegExp(`\\r\\n|[\\r\\n${LINE_SEPARATOR}${PARAGRAPH_SEPARATOR}]`);

const OPTIONS_TYPE = `export type Options<
  TData extends TDataShape = TDataShape,
  ThrowOnError extends boolean = boolean,
> = ClientOptions<TData, ThrowOnError> & {
  /**
   * You can provide a client instance returned by \`createClient()\` instead of
   * individual options. This might be also useful if you want to implement a
   * custom client.
   */
  client?: Client;
  /**
   * You can pass arbitrary values through the \`meta\` object. This can be
   * used to access values that aren't defined as part of the SDK function.
   */
  meta?: Record<string, unknown>;
};`;

const CREATE_CLIENT_CONFIG_TYPE = `/**
 * The \`createClientConfig()\` function will be called on client initialization
 * and the returned object will become the client's initial configuration.
 *
 * You may want to initialize your client this way instead of calling
 * \`setConfig()\`. This is useful for example if you're using Next.js
 * to ensure your client always has the correct values.
 */
export type CreateClientConfig<T extends DefaultClientOptions = ClientOptions> = (
  override?: Config<DefaultClientOptions & T>,
) => Config<Required<DefaultClientOptions> & T>;`;

export interface AugmentationOptions {
  /**
   * Prefixes of the QueryMap and MutationMap keys, e.g. `xmc.sites`.
   */
  namespaces: string[];
  /**
   * Deprecation message added to every key.
   */
  deprecated?: string;
}

/**
 * Wraps the generated types in a namespace, with `ClientOptions` last. Returns the code and
 * the names of the exported types.
 */
export function wrapTypes(source: string, namespace: string): { code: string; names: Set<string> } {
  const file = ts.createSourceFile('types.gen.ts', source, ts.ScriptTarget.Latest, true);
  const names = new Set<string>();
  const statements: string[] = [];
  let clientOptions: string | undefined;
  let end = 0;

  for (const statement of file.statements) {
    const start = statement.getStart(file, true);
    const trivia = source.slice(end, start);
    if ((end === 0 ? trivia.replace(HEADER, '') : trivia).trim()) {
      throw new Error(`Unexpected content in the generated types: ${trivia.trim()}`);
    }
    end = statement.end;

    const name = exportedName(statement, file);
    names.add(name);

    const text = source.slice(start, statement.end);
    if (name === 'ClientOptions') {
      assertClientOptions(statement);
      clientOptions = text;
    } else {
      statements.push(text);
    }
  }

  if (source.slice(end).trim()) {
    throw new Error(`Unexpected content in the generated types: ${source.slice(end).trim()}`);
  }

  if (!clientOptions) {
    throw new Error('The generated types have no ClientOptions type');
  }

  statements.push(clientOptions);

  return {
    code: `${HEADER}\n\nexport namespace ${namespace} {\n${statements.join('\n')}\n}\n`,
    names,
  };
}

function exportedName(statement: ts.Statement, file: ts.SourceFile): string {
  const exported =
    ts.canHaveModifiers(statement) &&
    ts.getModifiers(statement)?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword);

  if (exported) {
    if (ts.isTypeAliasDeclaration(statement) || ts.isInterfaceDeclaration(statement)) {
      return statement.name.text;
    }

    if (ts.isVariableStatement(statement)) {
      const [declaration, ...rest] = statement.declarationList.declarations;
      if (declaration && !rest.length && ts.isIdentifier(declaration.name)) {
        return declaration.name.text;
      }
    }
  }

  throw new Error(`Unexpected statement in the generated types: ${statement.getText(file)}`);
}

/**
 * Guards against a schema named `ClientOptions` taking the name of the client options type.
 */
function assertClientOptions(statement: ts.Statement): void {
  const members =
    ts.isTypeAliasDeclaration(statement) && ts.isTypeLiteralNode(statement.type)
      ? statement.type.members
      : [];

  if (
    members.length !== 1 ||
    !members[0].name ||
    !ts.isIdentifier(members[0].name) ||
    members[0].name.text !== 'baseUrl'
  ) {
    throw new Error('ClientOptions is not the client options type. Rename the conflicting schema.');
  }
}

export function emitSdk(operations: Operation[], namespace: string, httpModule: string): string {
  const serializers = unique(
    operations.flatMap(({ body }) => {
      switch (body?.type) {
        case 'form-data':
          return ['formDataBodySerializer'];
        case 'url-search-params':
          return ['urlSearchParamsBodySerializer'];
        default:
          return [];
      }
    }),
  );

  const clientImport = serializers.length
    ? `import { type Options as ClientOptions, type TDataShape, type Client, ${serializers.join(', ')} } from ${stringLiteral(httpModule)};`
    : `import type { Options as ClientOptions, TDataShape, Client } from ${stringLiteral(httpModule)};`;

  // Aliases are listed from the last operation to the first, as in the previous generator
  const aliases = unique(
    operations.flatMap(({ types }) =>
      [types.data, types.response, types.error].filter((name): name is string => !!name),
    ),
  ).reverse();

  return blocks([
    HEADER,
    [
      clientImport,
      `import type { ${namespace} } from './types.gen';`,
      `import { client as _heyApiClient } from './client.gen';`,
    ].join('\n'),
    ...aliases.map((name) => `type ${name} = ${namespace}.${name};`),
    OPTIONS_TYPE,
    ...operations.map(sdkFunction),
  ]);
}

function sdkFunction(operation: Operation): string {
  const optional = operation.optionsRequired ? '' : '?';
  const { data, response = 'unknown', error = 'unknown' } = operation.types;
  const comment = sdkComment(operation);

  return [
    ...(comment ? [comment] : []),
    `export const ${operation.id} = <ThrowOnError extends boolean = false>(`,
    `  options${optional}: Options<${data}, ThrowOnError>,`,
    ') => {',
    `  return (options${optional}.client ?? _heyApiClient).${operation.method}<${response}, ${error}, ThrowOnError>({`,
    ...requestOptions(operation).map((line) => `    ${line}`),
    '  });',
    '};',
  ].join('\n');
}

function requestOptions(operation: Operation): string[] {
  const lines: string[] = [];

  switch (operation.body?.type) {
    case 'form-data':
      lines.push('...formDataBodySerializer,');
      break;
    case 'url-search-params':
      lines.push('...urlSearchParamsBodySerializer,');
      break;
    case 'octet-stream':
    case 'text':
      lines.push('bodySerializer: null,');
      break;
  }

  if (operation.arrayQueryExplode === false) {
    lines.push(
      'querySerializer: {',
      '  array: {',
      '    explode: false,',
      "    style: 'form',",
      '  },',
      '},',
    );
  }

  if (operation.security.length) {
    lines.push('security: [');
    for (const security of operation.security) {
      lines.push('  {');
      for (const [key, value] of Object.entries(security)) {
        lines.push(`    ${key}: ${stringLiteral(value)},`);
      }
      lines.push('  },');
    }
    lines.push('],');
  }

  lines.push(`url: ${stringLiteral(operation.path)},`, '...options,');

  if (operation.body) {
    const contentType =
      operation.body.type === 'form-data' ? 'null' : stringLiteral(operation.body.mediaType);
    lines.push('headers: {', `  'Content-Type': ${contentType},`, '  ...options?.headers,', '},');
  }

  return lines;
}

function sdkComment(operation: Operation): string | undefined {
  const lines = [
    operation.deprecated ? '@deprecated' : undefined,
    operation.summary ? escapeComment(operation.summary) : undefined,
    operation.description ? escapeComment(operation.description) : undefined,
  ].filter((line): line is string => line !== undefined);

  if (!lines.length) {
    return undefined;
  }

  const body = lines
    .join('\n')
    .split(/\r\n?|\n/)
    .map((line) => ` * ${line}`)
    .join('\n');

  return printBlockComment(`*\n${body}\n `, 0);
}

function escapeComment(value: string): string {
  return value
    .replace(/\*\//g, '*')
    .replace(/\/\*/g, '*')
    .replace(/\r?\n(.*)/g, (_line, text: string) => `\n${text.trim()}`);
}

export function emitClient(
  namespace: string,
  baseUrl: string,
  httpModule: string,
  hostFetch: boolean,
): string {
  return blocks([
    HEADER,
    [
      `import type { ${namespace} } from './types.gen';`,
      `import { type Config, type ClientOptions as DefaultClientOptions, createClient, createConfig } from ${stringLiteral(httpModule)};`,
      ...(hostFetch ? ["import { clientSdkfetch } from '../client-sdk-fetch';"] : []),
    ].join('\n'),
    `type ClientOptions = ${namespace}.ClientOptions;`,
    CREATE_CLIENT_CONFIG_TYPE,
    [
      'export const client = createClient(',
      '  createConfig<ClientOptions>({',
      `    baseUrl: ${stringLiteral(baseUrl)},`,
      ...(hostFetch ? ['    fetch: clientSdkfetch,'] : []),
      '  }),',
      ');',
    ].join('\n'),
  ]);
}

/**
 * Declares the operations in the client's QueryMap (GET) and MutationMap (other methods).
 */
export function emitAugmentation(
  operations: Operation[],
  { namespaces, deprecated }: AugmentationOptions,
): string {
  const maps: Record<'QueryMap' | 'MutationMap', string[]> = { QueryMap: [], MutationMap: [] };

  for (const operation of operations) {
    const query = operation.method === 'get';
    for (const namespace of namespaces) {
      maps[query ? 'QueryMap' : 'MutationMap'].push(
        augmentationEntry(operation, `${namespace}.${operation.id}`, query, deprecated),
      );
    }
  }

  return blocks([
    HEADER,
    "import * as sdk from './sdk.gen';",
    ...Object.entries(maps).map(([name, entries]) =>
      [
        `declare module ${stringLiteral(CLIENT_MODULE)} {`,
        ...(entries.length
          ? [`  interface ${name} {`, ...entries, '  }']
          : [`  interface ${name} {}`]),
        '}',
      ].join('\n'),
    ),
  ]);
}

function augmentationEntry(
  operation: Operation,
  key: string,
  query: boolean,
  deprecated: string | undefined,
): string {
  const description = operation.description || operation.summary || 'No summary available.';
  const comment = deprecated
    ? `\n * @deprecated ${deprecated}\n * \n * ${description}\n`
    : `\n *\n * ${description}\n`;

  return [
    // Printed at the indentation the previous generator used for interface members
    `    ${printBlockComment(comment.trim(), 8)}`,
    `    ${stringLiteral(key)}: {`,
    `      params: Parameters<typeof sdk.${operation.id}>[0];`,
    `      response: Awaited<ReturnType<typeof sdk.${operation.id}>>;`,
    ...(query ? ['      subscribe: false;'] : []),
    '    };',
  ].join('\n');
}

export function emitIndex(): string {
  return `${HEADER}\nexport * from './types.gen';\nexport * from './sdk.gen';\n`;
}

/**
 * Prints a block comment like the TypeScript printer prints a synthesized comment: lines after
 * the first are trimmed and indented by `indent` plus their own leading whitespace (tabs count
 * as 4 columns). Prettier keeps comments verbatim unless every line starts with `*`, so this
 * keeps the output identical to the previous generator.
 */
export function printBlockComment(text: string, indent: number): string {
  if (text.includes('*/')) {
    throw new Error(`Comments must not contain '*/': ${text}`);
  }

  return `/*${text}*/`
    .split(LINE_BREAK)
    .map((line, index) =>
      index === 0 ? line.trim() : ' '.repeat(indent + leadingIndent(line)) + line.trim(),
    )
    .join('\n');
}

function leadingIndent(line: string): number {
  let indent = 0;

  for (const char of line) {
    if (char === '\t') {
      indent += 4 - (indent % 4);
    } else if (isSingleLineWhiteSpace(char.charCodeAt(0))) {
      indent++;
    } else {
      break;
    }
  }

  return indent;
}

/**
 * Same as TypeScript's `isWhiteSpaceSingleLine`.
 */
function isSingleLineWhiteSpace(code: number): boolean {
  return (
    code === 0x20 ||
    code === 0x09 ||
    code === 0x0b ||
    code === 0x0c ||
    code === 0xa0 ||
    code === 0x85 ||
    code === 0x1680 ||
    (code >= 0x2000 && code <= 0x200b) ||
    code === 0x202f ||
    code === 0x205f ||
    code === 0x3000 ||
    code === 0xfeff
  );
}

/**
 * Single-quoted string literal. Control characters and line breaks are rejected.
 */
export function stringLiteral(value: string): string {
  if (/[\x00-\x1f\x7f]/.test(value) || LINE_BREAK.test(value)) {
    throw new Error(`Unsupported characters in ${JSON.stringify(value)}`);
  }

  return `'${value.replace(/[\\']/g, '\\$&')}'`;
}

function blocks(items: string[]): string {
  return `${items.join('\n\n')}\n`;
}

function unique(values: string[]): string[] {
  return [...new Set(values)];
}
