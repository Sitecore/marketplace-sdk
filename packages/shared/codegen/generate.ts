import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createClient } from '@hey-api/openapi-ts';
import * as prettier from 'prettier';
import {
  type AugmentationOptions,
  emitAugmentation,
  emitClient,
  emitIndex,
  emitSdk,
  wrapTypes,
} from './emit';
import { assertIdentifier, collectOperations, type TypeLookup } from './operations';
import { DECLARED_ADDITIONAL_PROPERTIES, loadSpec, preprocessSpec } from './spec';

export interface GenerateConfig {
  /**
   * Path of the OpenAPI 3 document (JSON or YAML).
   */
  input: string;
  /**
   * Output directory. Files generated by a previous run are replaced.
   */
  output: string;
  /**
   * Namespace that wraps the generated types, e.g. `Sites`.
   */
  namespace: string;
  /**
   * Default `baseUrl` of the client. Takes precedence over `basePath`.
   */
  baseUrl?: string;
  /**
   * Path appended to `https://example.com` and used as the default `baseUrl`. When neither
   * `baseUrl` nor `basePath` is set, the first server URL of the spec is used.
   */
  basePath?: string;
  /**
   * Sends the requests through the host application with `clientSdkfetch` from
   * `../client-sdk-fetch`.
   */
  hostFetch?: boolean;
  /**
   * Declares the operations in the client's QueryMap and MutationMap.
   */
  augmentation?: AugmentationOptions;
}

const HTTP_MODULE = fileURLToPath(new URL('../src/http', import.meta.url));

const GENERATED_FILE = /^(?:[\w-]+\.gen\.ts|index\.ts)$/;

/**
 * The parts of the `@hey-api/typescript` plugin instance used to look up type names.
 */
interface TypeScriptPlugin {
  symbolFactory: {
    queryAll(filter: Record<string, unknown>): { finalName: string }[];
  };
}

/**
 * Generates a typed client for an OpenAPI spec: `types.gen.ts` (by `@hey-api/typescript`,
 * wrapped in a namespace), `client.gen.ts`, `sdk.gen.ts`, `index.ts` and, optionally,
 * `augmentation.gen.ts`.
 */
export async function generate(config: GenerateConfig): Promise<void> {
  assertIdentifier(config.namespace, 'namespace');

  const spec = preprocessSpec(loadSpec(config.input), {
    baseUrl: config.baseUrl,
    basePath: config.basePath,
  });
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sdk-codegen-'));

  try {
    const [context] = await createClient({
      input: spec,
      output: { path: temp, clean: true, entryFile: false },
      parser: { filters: { orphans: true }, transforms: { readWrite: false } },
      plugins: [
        {
          name: '@hey-api/typescript',
          enums: 'javascript',
          $resolvers: {
            // The previous generator typed an object schema without properties as `{}` when its
            // declared `additionalProperties` schema allows any value. Keep that type rather than
            // `{ [key: string]: unknown }`, which does not accept values of interface types.
            object: (ctx) => {
              const { additionalProperties, patternProperties, properties } = ctx.schema;

              return !properties &&
                !patternProperties &&
                additionalProperties &&
                additionalProperties.type === 'unknown' &&
                additionalProperties[DECLARED_ADDITIONAL_PROPERTIES]
                ? ctx.nodes.shape(ctx)
                : undefined;
            },
          },
        },
      ],
      logs: { level: 'warn', file: false },
      interactive: false,
    });

    if (!context) {
      throw new Error(`Failed to generate types for ${config.input}`);
    }

    const types = wrapTypes(
      fs.readFileSync(path.join(temp, 'types.gen.ts'), 'utf8'),
      config.namespace,
    );

    if (types.names.has(config.namespace)) {
      throw new Error(`Type '${config.namespace}' conflicts with the namespace`);
    }

    const plugin = context.plugins['@hey-api/typescript'] as unknown as TypeScriptPlugin;

    const lookupType: TypeLookup = (operationId, role) => {
      const symbols = plugin.symbolFactory.queryAll({
        artifact: 'types',
        category: 'type',
        resource: 'operation',
        resourceId: operationId,
        role,
      });

      if (symbols.length > 1) {
        throw new Error(`Found ${symbols.length} ${role} types for operation '${operationId}'`);
      }

      const name = symbols[0]?.finalName;
      if (name !== undefined && !types.names.has(name)) {
        throw new Error(`Type '${name}' of operation '${operationId}' was not generated`);
      }

      return name;
    };

    const operations = collectOperations(context.ir, lookupType);
    const httpModule = importPath(config.output, HTTP_MODULE);

    const files: Record<string, string> = {
      'types.gen.ts': types.code,
      'client.gen.ts': emitClient(
        config.namespace,
        spec.servers[0].url,
        httpModule,
        Boolean(config.hostFetch),
      ),
      'sdk.gen.ts': emitSdk(operations, config.namespace, httpModule),
      ...(config.augmentation && {
        'augmentation.gen.ts': emitAugmentation(operations, config.augmentation),
      }),
      'index.ts': emitIndex(),
    };

    for (const [name, code] of Object.entries(files)) {
      files[name] = await format(path.join(config.output, name), code);
    }

    cleanOutput(config.output);

    for (const [name, code] of Object.entries(files)) {
      fs.writeFileSync(path.join(config.output, name), code);
    }
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
}

async function format(file: string, code: string): Promise<string> {
  const options = await prettier.resolveConfig(file);
  return prettier.format(code, { ...options, filepath: file });
}

/**
 * Module specifier of `target` relative to `directory`.
 */
function importPath(directory: string, target: string): string {
  const relative = path.relative(path.resolve(directory), target);

  // On Windows, paths on different drives have no relative path
  if (path.isAbsolute(relative)) {
    throw new Error(`${directory} must be on the same drive as ${target}`);
  }

  const specifier = relative.split(path.sep).join('/');
  return specifier === '..' || specifier.startsWith('../') ? specifier : `./${specifier}`;
}

/**
 * Removes the files of a previous run, and refuses to touch a directory with other content.
 */
function cleanOutput(directory: string): void {
  fs.mkdirSync(directory, { recursive: true });

  const entries = fs.readdirSync(directory, { withFileTypes: true });
  const unexpected = entries.filter((entry) => !entry.isFile() || !GENERATED_FILE.test(entry.name));

  if (unexpected.length) {
    throw new Error(
      `${directory} contains files that were not generated: ${unexpected.map((entry) => entry.name).join(', ')}`,
    );
  }

  for (const entry of entries) {
    fs.rmSync(path.join(directory, entry.name));
  }
}
